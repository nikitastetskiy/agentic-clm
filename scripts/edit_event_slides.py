def reading_order(slots: list) -> list:
    """Top-to-bottom, left-to-right. Round y to a row band so a near-equal row sorts by x."""
    def key(sp):
        x, y = px.shape_xy(sp)
        return (round(y or 0), x or 0)
    return sorted(slots, key=key)


def collapse_into_first_run(p, text: str) -> bool:
    runs = px.para_runs(p)
    if not runs:
        return False
    px.set_run_text(runs[0], text)
    for r in runs[1:]:
        px.remove_node(r)
    return True


def fill_description(desc_sp, points: list[str], max_points: int = 3) -> int:
    """Render 2-3 description bullets by reusing the placeholder's EXISTING paragraph templates
    (so each point keeps the slide's own bullet/indent/font). One point per paragraph; if there are
    more points than template paragraphs, the last paragraph is cloned to hold them; surplus template
    paragraphs are removed. Returns how many points were written."""
    points = [p.strip() for p in (points or []) if p and p.strip()][:max_points]
    paras = px.paragraphs(desc_sp)
    if not paras or not points:
        return 0
    while len(paras) < len(points):  # grow by cloning the last bullet template
        clone = paras[-1].cloneNode(True)
        paras[-1].parentNode.appendChild(clone)
        paras.append(clone)
    n = len(points)
    for i in range(n):
        collapse_into_first_run(paras[i], points[i])
    for p in paras[n:]:
        px.remove_node(p)
    return n


def fit_title(title_sp, text: str) -> bool:
    """Stop a long featured-event title from overflowing the Register link below it.

    The title box uses <a:spAutoFit/> (the SHAPE grows to fit text), so a title that wraps to a
    second line expands the box down over the 'Subtitle 2' link. Swap to <a:normAutofit/> (fixed
    box, shrink text) with a length-based fontScale so long titles render on one line. Short titles
    are left untouched. Run formatting (size/colour/font) is never altered — only the box autofit."""
    bodies = title_sp.getElementsByTagName("a:bodyPr")
    if not bodies:
        return False
    body = bodies[0]
    n = len(text or "")
    if n <= 40:  # comfortably fits one line at full size — leave the original spAutoFit
        return False
    scale = "90000" if n <= 48 else "80000" if n <= 56 else "70000"
    for tag in ("a:spAutoFit", "a:normAutofit", "a:noAutofit"):
        for el in list(body.getElementsByTagName(tag)):
            px.remove_node(el)
    naf = title_sp.ownerDocument.createElement("a:normAutofit")
    naf.setAttribute("fontScale", scale)
    body.appendChild(naf)
    return True


def _pic_geom(pic):
    x = pic.getElementsByTagName("a:xfrm")
    if not x:
        return None
    ext = x[0].getElementsByTagName("a:ext")
    if not ext:
        return None
    return (int(ext[0].getAttribute("cx")), int(ext[0].getAttribute("cy")))


def _img_size(path: Path):
    """(width, height) in pixels. Reads the PNG IHDR directly (no deps); falls back to Pillow for
    other formats. Returns None if the size can't be determined."""
    try:
        head = path.read_bytes()[:24]
        if head[:8] == b"\x89PNG\r\n\x1a\n" and head[12:16] == b"IHDR":
            w, h = struct.unpack(">II", head[16:24])
            return (w, h)
    except Exception:
        pass
    try:
        from PIL import Image  # lazy: only needed for non-PNG captures
        with Image.open(path) as im:
            return im.size
    except Exception:
        return None


def _cover_srcrect(frame_cx: int, frame_cy: int, img_w: int, img_h: int) -> dict:
    """Crop rectangle (a:srcRect, units of 1/1000 of a percent) that makes the image fill the frame
    WITHOUT distortion ("cover"): when the source is taller than the frame we crop top/bottom and keep
    the FULL WIDTH (so the gradient background spans the slide); when it is wider we crop left/right and
    keep the full height. Returns {} when the aspect ratios already match (no crop needed)."""
    if not (frame_cx and frame_cy and img_w and img_h):
        return {}
    ar_f = frame_cx / frame_cy
    ar_i = img_w / img_h
    if abs(ar_f - ar_i) < 1e-4:
        return {}
    if ar_f > ar_i:                      # frame wider -> crop height, keep full width
        c = round((1 - ar_i / ar_f) / 2 * 100000)
        return {"t": c, "b": c}
    c = round((1 - ar_f / ar_i) / 2 * 100000)   # image wider -> crop width, keep full height
    return {"l": c, "r": c}


def _pic_xfrm(pic):
    """(x, y, cx, cy) of a picture, or None."""
    xf = pic.getElementsByTagName("a:xfrm")
    if not xf:
        return None
    off = xf[0].getElementsByTagName("a:off")
    ext = xf[0].getElementsByTagName("a:ext")
    if not off or not ext:
        return None
    return (int(off[0].getAttribute("x")), int(off[0].getAttribute("y")),
            int(ext[0].getAttribute("cx")), int(ext[0].getAttribute("cy")))


def flag_pics(dom) -> list:
    """The circular language-flag icons (small, ~square, prstGeom ellipse) on a webinar slide, as
    (pic, center_xy). The size/aspect guard avoids grabbing any larger decorative ellipse."""
    out = []
    for pic in dom.getElementsByTagName("p:pic"):
        if not any(g.getAttribute("prst") == "ellipse"
                   for g in pic.getElementsByTagName("a:prstGeom")):
            continue
        g = _pic_xfrm(pic)
        if not g:
            continue
        cx, cy = g[2], g[3]
        if cx > 600000 or cy > 600000 or not (0.6 <= (cx / cy if cy else 0) <= 1.6):
            continue
        out.append((pic, (g[0] + cx // 2, g[1] + cy // 2)))
    return out


def flag_for_slot(slot_sp, flags: list, used: set):
    """The flag pic that belongs to a slot: the (unused) ellipse whose centre falls inside the slot's
    box; falls back to the nearest unused flag centre. Returns the pic element or None."""
    x, y = px.shape_xy(slot_sp)
    ext = None
    xf = slot_sp.getElementsByTagName("a:xfrm")
    if xf:
        e = xf[0].getElementsByTagName("a:ext")
        if e:
            ext = (int(e[0].getAttribute("cx")), int(e[0].getAttribute("cy")))
    inside = []
    for pic, (cx, cy) in flags:
        if id(pic) in used:
            continue
        if ext and x <= cx <= x + ext[0] and y <= cy <= y + ext[1]:
            inside.append((pic, (cx, cy)))
    pool = inside or [(p, c) for p, c in flags if id(p) not in used]
    if not pool:
        return None
    sx, sy = (x or 0), (y or 0)
    pic = min(pool, key=lambda t: (t[1][0] - sx) ** 2 + (t[1][1] - sy) ** 2)[0]
    used.add(id(pic))
    return pic


def set_slot_flag(pic, rels_dom, root: Path, slide_n, idx: int, lang: str):
    """Repoint a slot's circular flag to assets/flags/<lang>.png (fresh media + rel) and update its alt
    text. No-op (returns None) when the flag is already that language or the asset is missing."""
    lang = lang if lang in FLAG_DESCR else "en"
    asset = FLAG_DIR / f"{lang}.png"
    if not asset.exists():
        return None
    cnv = pic.getElementsByTagName("p:cNvPr")
    cur = cnv[0].getAttribute("descr") if cnv else ""
    if _descr_lang(cur) == lang:
        return None
    blips = pic.getElementsByTagName("a:blip")
    if not blips:
        return None
    media = root / "ppt" / "media"
    media.mkdir(parents=True, exist_ok=True)
    newname = f"image_flag_s{slide_n}_{idx}.png"
    shutil.copy(asset, media / newname)
    blips[0].setAttribute("r:embed", px.add_image_rel(rels_dom, f"../media/{newname}"))
    if cnv:
        cnv[0].setAttribute("descr", FLAG_DESCR[lang])
    return {"slot": idx, "language": lang}


def _descr_lang(descr: str):
    d = (descr or "").lower()
    for kw, code in _DESCR_LANG:
        if kw in d:
            return code
    return None


def find_hero_pic(dom):
    """Pick the slide's event-photo picture. The template's event hero is an explicit 'Picture
    Placeholder' on most featured slides, so prefer that (excluding the full-bleed background = the
    single largest pic). When no placeholder exists, fall back to the largest remaining picture that
    isn't a tiny logo (>1% of the background). Returns the <p:pic> element or None (photo left as-is)."""
    pics = []
    for pic in dom.getElementsByTagName("p:pic"):
        g = _pic_geom(pic)
        if not g:
            continue
        name = pic.getElementsByTagName("p:cNvPr")[0].getAttribute("name")
        pics.append((g[0] * g[1], name, pic))
    if len(pics) < 2:
        return None
    pics.sort(key=lambda t: t[0], reverse=True)
    bg_area = pics[0][0]
    rest = pics[1:]  # exclude the full-bleed background (single largest)
    placeholders = [t for t in rest if "placeholder" in t[1].lower()]
    if placeholders:
        return max(placeholders, key=lambda t: t[0])[2]
    cands = [t for t in rest if t[0] > 0.01 * bg_area]
    if not cands:
        return None
    return max(cands, key=lambda t: t[0])[2]


def _rel_target(rels_dom, rid: str) -> str:
    for rel in rels_dom.getElementsByTagName("Relationship"):
        if rel.getAttribute("Id") == rid:
            return rel.getAttribute("Target")
    return ""


def _pic_media_basename(pic, rels_dom) -> str:
    """The media filename a picture currently embeds (e.g. 'image46.png'), or '' if unknown."""
    blips = pic.getElementsByTagName("a:blip")
    if not blips:
        return ""
    tgt = _rel_target(rels_dom, blips[0].getAttribute("r:embed"))
    return tgt.rsplit("/", 1)[-1] if tgt else ""


def _set_xfrm(node, off, ext) -> bool:
    """Set a shape/picture's a:off + a:ext (EMU). No-op (returns False) if it has no a:xfrm."""
    xs = node.getElementsByTagName("a:xfrm")
    if not xs:
        return False
    offs = xs[0].getElementsByTagName("a:off")
    exts = xs[0].getElementsByTagName("a:ext")
    if offs:
        offs[0].setAttribute("x", str(off[0])); offs[0].setAttribute("y", str(off[1]))
    if exts:
        exts[0].setAttribute("cx", str(ext[0])); exts[0].setAttribute("cy", str(ext[1]))
    return bool(offs and exts)


def _sp_box(sp):
    xs = sp.getElementsByTagName("a:xfrm")
    if not xs:
        return None
    off = xs[0].getElementsByTagName("a:off")
    ext = xs[0].getElementsByTagName("a:ext")
    if not (off and ext):
        return None
    return (int(off[0].getAttribute("x")), int(off[0].getAttribute("y")),
            int(ext[0].getAttribute("cx")), int(ext[0].getAttribute("cy")))


def _overlaps(a, b) -> bool:
    ax, ay, acx, acy = a
    bx, by, bcx, bcy = b
    return not (ax + acx <= bx or bx + bcx <= ax or ay + acy <= by or by + bcy <= ay)


def normalize_small_hero(dom, by_name, hero_pic) -> bool:
    """If a featured slide's hero placeholder is much smaller than the canonical event hero (the deck's
    one webinar-derived featured slide), resize/reposition the hero — and the title + subtitle — to the
    canonical geometry and clear any stray text box that would sit over the enlarged hero, so the slide
    matches the other featured events. Returns True if it normalized."""
    g = _pic_geom(hero_pic)
    if not g:
        return False
    if g[0] * g[1] >= 0.5 * (CANON_HERO[2] * CANON_HERO[3]):
        return False
    _set_xfrm(hero_pic, CANON_HERO[:2], CANON_HERO[2:])
    if by_name.get(FEATURED_TITLE):
        _set_xfrm(by_name[FEATURED_TITLE], CANON_TITLE[:2], CANON_TITLE[2:])
    if by_name.get(FEATURED_DATE):
        _set_xfrm(by_name[FEATURED_DATE], CANON_SUBTITLE[:2], CANON_SUBTITLE[2:])
    keep = {FEATURED_TITLE, FEATURED_DATE, FEATURED_DESC}
    for sp in dom.getElementsByTagName("p:sp"):
        if px.shape_name(sp) in keep:
            continue
        box = _sp_box(sp)
        if box and _overlaps(box, CANON_HERO):
            clear_txbody(sp)
    return True


def normalize_secondary_pics(dom, rels_dom, hero_pic, event: dict) -> list:
    """Keep one hero per featured slide. The full-bleed background and the small corner brand logo are
    always kept; a static city photo is kept only when it matches the event's city; every other non-hero
    extra picture (e.g. a leftover product logo, or a city photo for the wrong city) is removed."""
    pics = []
    for pic in dom.getElementsByTagName("p:pic"):
        g = _pic_geom(pic)
        if not g:
            continue
        nm = pic.getElementsByTagName("p:cNvPr")[0].getAttribute("name")
        pics.append((g[0] * g[1], nm, pic))
    if not pics:
        return []
    bg_area = max(a for a, _, _ in pics)
    loc = f"{event.get('location', '')} {event.get('title', '')}".lower()
    removed = []
    for area, nm, pic in pics:
        if pic is hero_pic or area >= bg_area or area < 0.012 * bg_area:
            continue  # hero, full-bleed background, or tiny corner logo
        base = _pic_media_basename(pic, rels_dom)
        city = SECONDARY_CITY_PHOTOS.get(base)
        if city and city in loc:
            continue  # correct city skyline beside the hero -> keep
        px.remove_node(pic)
        removed.append({"shape": nm, "media": base,
                        "reason": "city-mismatch" if city else "non-hero-extra"})
    return removed


def pick_event_image(event: dict, manifest: dict, fallbacks: list[dict]) -> dict | None:
    """Choose the image record for an event.

    Prefer the event's OWN per-page capture (the decluttered IBM city leadspace hero — title + brand
    gradient), so each featured slide shows its own city. A configured HashiCorp SERIES hero is used
    only as a FALLBACK when the event has no quality-approved own capture (e.g. the Hands-On Lab page
    exposes no leadspace). Both paths require `status == "ok"` and a file.
    """
    title = event.get("title", "")
    own = manifest.get(event.get("url", ""))
    if own and own.get("status") == "ok" and own.get("file"):
        rec = dict(own)
        rec["_source_kind"] = "own"
        rec["_source_id"] = own.get("url")
        return rec
    for fb in fallbacks:
        if (fb.get("status") == "ok" and fb.get("file") and fb.get("match")
                and re.search(fb["match"], title, re.I)):
            rec = dict(fb)
            rec["_source_kind"] = "series"
            rec["_source_id"] = fb.get("id")
            return rec
    return None


def image_source_summary(image_rec: dict | None) -> dict | None:
    if not image_rec:
        return None
    return {
        "kind": image_rec.get("_source_kind") or ("series" if image_rec.get("id") else "own"),
        "id": image_rec.get("_source_id") or image_rec.get("id") or image_rec.get("url"),
        "file": image_rec.get("file"),
        "url": image_rec.get("url"),
    }


def swap_event_image(dom, rels_dom, root: Path, slide_n: int, img_path: Path):
    """Replace the slide's event-photo with the captured leadspace screenshot by adding the image as
    a FRESH media file + relationship and repointing the picture's <a:blip r:embed> (never mutating a
    shared image rel or overwriting existing media). Returns info dict, or None if no suitable pic."""
    pic = find_hero_pic(dom)
    if pic is None:
        return None
    blips = pic.getElementsByTagName("a:blip")
    if not blips:
        return None
    media = root / "ppt" / "media"
    media.mkdir(parents=True, exist_ok=True)
    newname = f"image_evt_slide{slide_n}{img_path.suffix.lower() or '.png'}"
    shutil.copy(img_path, media / newname)
    rid = px.add_image_rel(rels_dom, f"../media/{newname}")
    blips[0].setAttribute("r:embed", rid)
    # The old per-event crop (a:srcRect) was tuned to the previous photo. Replace it with a "cover"
    # crop computed from THIS capture's pixel size vs the frame: crop top/bottom (keep full width, so
    # the gradient spans the slide) when the hero is taller than the frame, or left/right when wider.
    # This makes the screenshot fill the frame with NO horizontal/vertical stretching.
    blip = blips[0]
    blipfill = blip.parentNode
    for sr in pic.getElementsByTagName("a:srcRect"):
        sr.parentNode.removeChild(sr)
    geom = _pic_geom(pic)
    size = _img_size(img_path)
    crop = _cover_srcrect(geom[0], geom[1], size[0], size[1]) if geom and size else {}
    if crop:
        sr = pic.ownerDocument.createElement("a:srcRect")
        for k, v in crop.items():
            sr.setAttribute(k, str(v))
        blipfill.insertBefore(sr, blip.nextSibling)
    name = pic.getElementsByTagName("p:cNvPr")[0].getAttribute("name")
    return {"shape": name, "media": newname, "embed": rid, "srcRect": crop or None}


def clear_txbody(sp) -> None:
    """Reduce a shape to a single empty paragraph (matches a hand-cleared slot)."""
    bodies = sp.getElementsByTagName("p:txBody")
    if not bodies:
        return
    body = bodies[0]
    for p in list(body.getElementsByTagName("a:p")):
        px.remove_node(p)
    doc = sp.ownerDocument
    p = doc.createElement("a:p")
    epr = doc.createElement("a:endParaRPr")
    epr.setAttribute("lang", "en-US")
    p.appendChild(epr)
    body.appendChild(p)


def fill_webinar_slot(sp, rels_dom, e: dict) -> bool:
    paras = px.paragraphs(sp)
    if len(paras) < 2:
        return False
    runs0 = px.para_runs(paras[0])
    see_idx = next((i for i, r in enumerate(runs0) if px.run_hyperlink(r) is not None), None)
    if see_idx is None or see_idx == 0:
        return False
    px.set_run_text(runs0[0], f"{e['date_label']} | {e['kind']} | ")
    for r in runs0[1:see_idx]:
        px.remove_node(r)
    px.run_hyperlink(runs0[see_idx]).setAttribute("r:id", px.add_rel(rels_dom, e["url"]))
    collapse_into_first_run(paras[1], e["title"])
    desc = (e.get("description") or "").strip()
    if len(paras) >= 3:
        if desc and collapse_into_first_run(paras[2], desc):
            for p in paras[3:]:
                px.remove_node(p)
        else:
            for p in paras[2:]:
                px.remove_node(p)
    return True


# --------------------------------------------------------------------------- slide editors --------
def webinar_slots(dom) -> list:
    return reading_order([sp for sp in dom.getElementsByTagName("p:sp")
                          if px.shape_name(sp) == WEBINAR_SHAPE])


def count_slots(slide_file: Path) -> int:
    return len(webinar_slots(minidom.parse(str(slide_file))))


def edit_webinar_slide(slide_file: Path, rels_file: Path, fill: list[dict],
                       root: Path = None, slide_n=None) -> dict:
    """Fill each slot from the precomputed `fill` list (primary product webinars + backfills, already
    allocated and de-duplicated globally). Only clears a slot if the pool ran dry (kept as a guard).
    Each filled slot's circular language flag is repointed to match the webinar's detected language."""
    dom = minidom.parse(str(slide_file))
    rels_dom, _ = px.load_rels(rels_file)
    slots = webinar_slots(dom)
    flags = flag_pics(dom) if root is not None else []
    used_flags = set()
    filled, backfilled, cleared, flag_changes = [], [], 0, []
    for i, sp in enumerate(slots):
        if i < len(fill) and fill_webinar_slot(sp, rels_dom, fill[i]):
            filled.append(fill[i]["title"])
            if fill[i].get("backfill"):
                backfilled.append(f"{fill[i]['kind']}: {fill[i]['title'][:50]}")
            if root is not None and flags:
                pic = flag_for_slot(sp, flags, used_flags)
                if pic is not None:
                    chg = set_slot_flag(pic, rels_dom, root, slide_n, i, fill[i].get("language", "en"))
                    if chg:
                        flag_changes.append(chg)
        else:
            clear_txbody(sp)
            cleared += 1
    hidden = len(filled) == 0
    if hidden:
        dom.documentElement.setAttribute("show", "0")
    pruned = px.prune_orphan_hyperlinks(dom, rels_dom)
    slide_file.write_text(dom.toxml(), encoding="utf-8")
    rels_file.write_text(rels_dom.toxml(), encoding="utf-8")
    return {"slots": len(slots), "filled": filled, "backfilled": backfilled, "cleared": cleared,
            "hidden": hidden, "available": len(fill), "pruned_rels": pruned, "flags": flag_changes}


def edit_featured_slide(slide_file: Path, rels_file: Path, event: dict | None,
                        root: Path | None = None, image_rec: dict | None = None,
                        slide_n: int | None = None) -> dict:
    dom = minidom.parse(str(slide_file))
    if event is None:
        dom.documentElement.setAttribute("show", "0")
        slide_file.write_text(dom.toxml(), encoding="utf-8")
        return {"hidden": True, "title": None}
    rels_dom, _ = px.load_rels(rels_file)
    by_name = {}
    for sp in dom.getElementsByTagName("p:sp"):
        by_name.setdefault(px.shape_name(sp), sp)

    title_sp = by_name.get(FEATURED_TITLE)
    title_fit = False
    if title_sp and px.paragraphs(title_sp):
        collapse_into_first_run(px.paragraphs(title_sp)[0], event["title"])
        title_fit = fit_title(title_sp, event["title"])

    date_sp = by_name.get(FEATURED_DATE)
    if date_sp and px.paragraphs(date_sp):
        p0 = px.paragraphs(date_sp)[0]
        runs = px.para_runs(p0)
        link_idx = next((i for i, r in enumerate(runs) if px.run_hyperlink(r) is not None), None)
        if link_idx is not None and link_idx > 0:
            px.set_run_text(runs[0], f"Event | {event['display_date']} | ")
            for r in runs[1:link_idx]:
                px.remove_node(r)
            px.run_hyperlink(runs[link_idx]).setAttribute("r:id", px.add_rel(rels_dom, event["url"]))

    desc_sp = by_name.get(FEATURED_DESC)
    points = event.get("description_points") or []
    if not points:
        single = (event.get("description") or "").strip()
        points = [single] if single else []
    desc_written = fill_description(desc_sp, points) if desc_sp else 0

    # Normalize the slide to the global single-hero featured style: enlarge a tiny webinar-derived hero
    # (and its title/subtitle) to canonical geometry, then drop extra pictures (stray logos, or a static
    # city photo that doesn't match THIS event's city).
    hero_pic = find_hero_pic(dom)
    hero_normalized = normalize_small_hero(dom, by_name, hero_pic) if hero_pic is not None else False

    image_swapped = None
    if root is not None and slide_n is not None and image_rec and image_rec.get("status") == "ok":
        img_path = (DATA_DIR.parent / image_rec["file"]).resolve()
        if img_path.exists():
            image_swapped = swap_event_image(dom, rels_dom, root, slide_n, img_path)

    secondary_removed = normalize_secondary_pics(dom, rels_dom, hero_pic, event) if hero_pic is not None else []

    pruned = px.prune_orphan_hyperlinks(dom, rels_dom)
    slide_file.write_text(dom.toxml(), encoding="utf-8")
    rels_file.write_text(rels_dom.toxml(), encoding="utf-8")
    return {"hidden": False, "title": event["title"], "date": event["display_date"],
            "desc_points": desc_written, "title_fit": title_fit,
            "image_swapped": bool(image_swapped), "image_source": image_source_summary(image_rec),
            "hero_normalized": hero_normalized, "secondary_removed": secondary_removed,
            "pruned_rels": pruned}


def slide_paths(root: Path, n: int) -> tuple[Path, Path]:
    sf = root / "ppt" / "slides" / f"slide{n}.xml"
    rf = root / "ppt" / "slides" / "_rels" / f"slide{n}.xml.rels"
    return sf, rf


def allocate_webinars(webinar_slides: list[tuple], webinars: dict, featured: list[dict],
                      reserved_featured_ids: set) -> dict:
    """Globally allocate slot-fill entries so no event repeats across slides and no in-scope slot is
    left blank while events remain. Each slide first takes its OWN product's webinars (soonest-first),
    then empty slots are backfilled from a shared pool of cross-product/other webinars + featured events
    NOT already shown on the in-person slides (18-22) — mirroring the hand-authored deck, which always
    filled every slot with cert/cross-product/regional sessions."""
    used = set()
    plan = {}
    # Pass 1 — primary product webinars.
    for n, product, slots in webinar_slides:
        chosen = []
        for w in sorted(webinars.get(product, []), key=lambda x: x.get("date", "")):
            if len(chosen) >= slots:
                break
            if _event_identity(w) in used:
                continue
            chosen.append(_entry(w, "WEBINAR"))
            used.add(_event_identity(w))
        plan[n] = chosen
    # Shared backfill pool — every remaining webinar (any bucket) + non-reserved featured.
    pool = []
    for bucket in webinars.values():
        for w in bucket:
            if _event_identity(w) not in used:
                pool.append(_entry(w, "WEBINAR"))
    for f in featured:
        if _event_identity(f) not in used and _event_identity(f) not in reserved_featured_ids:
            ent = _entry(f, f.get("type", "EVENT"))
            ent["backfill"] = True
            pool.append(ent)
    seen, dedup = set(), []
    for e in sorted(pool, key=lambda x: x["date"]):
        if _event_identity(e) in seen:
            continue
        seen.add(_event_identity(e))
        dedup.append(e)
    # Pass 2 — distribute the pool across empty slots in slide order.
    pi = 0
    for n, _product, slots in webinar_slides:
        while len(plan[n]) < slots and pi < len(dedup):
            e = dedup[pi]
            pi += 1
            if _event_identity(e) in used:
                continue
            e.setdefault("backfill", True)
            plan[n].append(e)
            used.add(_event_identity(e))
        plan[n].sort(key=lambda x: x["date"])  # soonest-first reading order, like the hand-authored deck
    return plan


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("deck")
    ap.add_argument("--report", default=str(DATA_DIR / "event-edit-report.json"))
    ap.add_argument("--original", default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    deck = Path(args.deck).resolve()
    if not deck.exists():
        raise SystemExit(f"deck not found: {deck}")
    if args.original and Path(args.original).resolve() == deck:
        raise SystemExit("refusing to edit the ORIGINAL deck in place")

    slide_map = load_config("slide-map.yaml")
    events = json.loads((DATA_DIR / "events.json").read_text(encoding="utf-8"))
    webinars = events.get("webinars", {})
    featured = sorted(events.get("featured", []), key=lambda e: e["date"])  # soonest first

    # Optional Playwright captures: quality-screened per-event screenshots (keyed by event URL) plus
    # on-brand series heroes. Matching series heroes are preferred for consistent featured-slide photos.
    image_manifest = {}
    image_fallbacks: list[dict] = []
    img_file = DATA_DIR / "event-images.json"
    if img_file.exists():
        try:
            _imgs = json.loads(img_file.read_text(encoding="utf-8"))
            image_manifest = _imgs.get("images", {})
            image_fallbacks = list((_imgs.get("fallbacks") or {}).values())
        except (ValueError, OSError):
            image_manifest = {}

    # Featured events shown on the in-person slides (18-22) are reserved — excluded from webinar
    # backfill so an event never appears twice in the deck. Key the reservation on _event_identity
    # (title+date), NOT url: several distinct featured events share a generic landing-page url (e.g.
    # AWS Summit DC / Mexico City / Zurich all link to aws.amazon.com/events/summits/), so a url-keyed
    # reservation would wrongly drop the non-reserved AWS Summits from the pool and starve a slide.
    inperson_ns = []
    for entry in slide_map.get("slides", []):
        if entry.get("type") == "in_person_event":
            ns = entry["n"]
            inperson_ns.extend(ns if isinstance(ns, list) else [ns])
    reserved_featured_ids = {_event_identity(f) for f in featured[:len(inperson_ns)]}

    tmp = Path(tempfile.mkdtemp(prefix="eventedit-"))
    report = {"slides": {}, "any_change": False}
    try:
        px.unpack(deck, tmp)
        # Collect webinar slides + their slot counts up front so allocation can span all of them.
        webinar_slides = []
        for entry in slide_map.get("slides", []):
            if entry.get("type") != "webinars":
                continue
            n = entry["n"]
            sf, _rf = slide_paths(tmp, n)
            if sf.exists():
                webinar_slides.append((n, entry["product"], count_slots(sf)))
        plan = allocate_webinars(webinar_slides, webinars, featured, reserved_featured_ids)

        for entry in slide_map.get("slides", []):
            etype = entry.get("type")
            if etype == "webinars":
                n = entry["n"]
                sf, rf = slide_paths(tmp, n)
                if not sf.exists():
                    continue
                rep = edit_webinar_slide(sf, rf, plan.get(n, []), root=tmp, slide_n=n)
                rep["product"] = entry["product"]
                report["slides"][str(n)] = rep
                report["any_change"] = True
            elif etype == "in_person_event":
                ns = entry["n"]
                ns = ns if isinstance(ns, list) else [ns]
                for i, n in enumerate(ns):
                    sf, rf = slide_paths(tmp, n)
                    if not sf.exists():
                        continue
                    ev = featured[i] if i < len(featured) else None
                    img_rec = pick_event_image(ev, image_manifest, image_fallbacks) if ev else None
                    report["slides"][str(n)] = edit_featured_slide(
                        sf, rf, ev, root=tmp, image_rec=img_rec, slide_n=n)
                    report["any_change"] = True
        if report["any_change"] and not args.dry_run:
            out = px.pack(tmp, deck)
            if out.returncode != 0:
                log(f"pack failed: {out.stderr[-600:]}")
                return 2
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    Path(args.report).write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    for n, s in sorted(report["slides"].items(), key=lambda kv: int(kv[0])):
        if "slots" in s:
            extra = f", backfilled {len(s['backfilled'])}" if s.get("backfilled") else ""
            flg = f", flags {[f['language'] for f in s['flags']]}" if s.get("flags") else ""
            log(f"slide {n} ({s.get('product')}): filled {len(s['filled'])}/{s['slots']} slots, "
                f"cleared {s['cleared']}{extra}{flg}" + ("  [HIDDEN: no webinars]" if s["hidden"] else ""))
            for t in s["filled"]:
                log(f"    - {t[:60]}")
        else:
            if s["hidden"]:
                log(f"slide {n}: HIDDEN (no featured event)")
            else:
                src = (s.get("image_source") or {}).get("kind")
                img = f"  [photo updated: {src}]" if s.get("image_swapped") and src else (
                    "  [photo updated]" if s.get("image_swapped") else "")
                norm = "  [hero enlarged]" if s.get("hero_normalized") else ""
                rm = s.get("secondary_removed") or []
                rmtxt = f"  [removed {len(rm)} extra pic(s): {', '.join(r['reason'] for r in rm)}]" if rm else ""
                log(f"slide {n}: {s['date']} :: {s['title'][:55]}{img}{norm}{rmtxt}")
    log(f"report -> {args.report}" + ("  [DRY-RUN, deck not written]" if args.dry_run else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
